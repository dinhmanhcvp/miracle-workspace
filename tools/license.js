#!/usr/bin/env node
/*
 * License tool for the vendor (you). No dependencies.
 *
 *   node tools/license.js keygen --vendor "Tên của bạn" --contact "email / Zalo"
 *       Creates the signing key pair. Private key -> ~/.koc-license/private.pem (keep it secret, never commit it).
 *       Public key -> assets/license-key.js (commit and deploy this).
 *   node tools/license.js issue --agency "ABC Media" --days 365 [--plan Pro] [--domains abc.pages.dev,abc.com]
 *       Prints a license key to send to the agency (they paste it in Cấu hình agency).
 *   node tools/license.js verify <key>
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const args = process.argv.slice(2);
const cmd = args[0];
const opt = (name, def) => { const i = args.indexOf('--' + name); return i > -1 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : (args.includes('--' + name) ? true : def); };
const KEY_DIR = opt('key-dir', path.join(os.homedir(), '.koc-license'));
const PRIV = opt('key', path.join(KEY_DIR, 'private.pem'));
const PUB_JS = opt('pub-out', path.join(__dirname, '..', 'assets', 'license-key.js'));
const b64url = (buf) => Buffer.from(buf).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

const readPublicJwk = () => {
    const src = fs.readFileSync(PUB_JS, 'utf8');
    const m = src.match(/LICENSE_PUBLIC_KEY\s*=\s*(\{[\s\S]*?\});/);
    if (!m) throw new Error('assets/license-key.js chưa có public key. Chạy: node tools/license.js keygen');
    return JSON.parse(m[1]);
};

if (cmd === 'keygen') {
    if (fs.existsSync(PRIV) && !opt('force')) {
        console.error(`Đã có private key tại ${PRIV}. Tạo lại sẽ làm MỌI mã bản quyền cũ mất hiệu lực. Thêm --force nếu chắc chắn.`);
        process.exit(1);
    }
    const { privateKey, publicKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'P-256' });
    fs.mkdirSync(path.dirname(PRIV), { recursive: true, mode: 0o700 });
    fs.writeFileSync(PRIV, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
    const jwk = publicKey.export({ format: 'jwk' });
    const vendor = { name: String(opt('vendor', '') === true ? '' : opt('vendor', '')), contact: String(opt('contact', '') === true ? '' : opt('contact', '')) };
    fs.writeFileSync(PUB_JS, `// Public key used to verify license keys. Generated by: node tools/license.js keygen
// null = licensing disabled (no trial, no lock): the tool is fully usable.
window.LICENSE_PUBLIC_KEY = ${JSON.stringify({ kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y })};
window.LICENSE_VENDOR = ${JSON.stringify(vendor)};
`);
    console.log(`Private key: ${PRIV}  (GIỮ BÍ MẬT, sao lưu an toàn, không commit)`);
    console.log(`Public key đã ghi vào ${path.relative(process.cwd(), PUB_JS)}  (commit và deploy file này)`);
} else if (cmd === 'issue') {
    const agency = opt('agency');
    if (!agency || agency === true) { console.error('Thiếu --agency "Tên agency"'); process.exit(1); }
    const days = Number(opt('days', 365));
    const now = new Date();
    const payload = { v: 1, id: crypto.randomUUID(), agency, plan: opt('plan', '') === true ? '' : opt('plan', ''), iat: now.toISOString(), exp: new Date(now.getTime() + days * 86400000).toISOString() };
    const domains = opt('domains');
    if (domains && domains !== true) payload.domains = domains.split(',').map(s => s.trim()).filter(Boolean);
    const data = Buffer.from(JSON.stringify(payload));
    const sig = crypto.sign('sha256', data, { key: fs.readFileSync(PRIV, 'utf8'), dsaEncoding: 'ieee-p1363' });
    console.log(`${b64url(data)}.${b64url(sig)}`);
    console.error(`\n${agency}: hết hạn ${payload.exp.slice(0, 10)}${payload.domains ? ', chỉ dùng trên ' + payload.domains.join(', ') : ''} (id ${payload.id})`);
} else if (cmd === 'verify') {
    const key = args[1] || '';
    const [p, s] = key.split('.');
    const pub = crypto.createPublicKey({ key: readPublicJwk(), format: 'jwk' });
    const ok = crypto.verify('sha256', Buffer.from(p, 'base64url'), { key: pub, dsaEncoding: 'ieee-p1363' }, Buffer.from(s, 'base64url'));
    console.log(ok ? 'Hợp lệ' : 'KHÔNG hợp lệ', ok ? JSON.parse(Buffer.from(p, 'base64url').toString()) : '');
    process.exit(ok ? 0 : 1);
} else {
    console.log(fs.readFileSync(__filename, 'utf8').split('\n').slice(1, 13).join('\n'));
}
